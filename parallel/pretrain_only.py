#!/usr/bin/env python3
"""Run only the pretraining phase of a benchmark command.

Creates the checkpoint that `run_single_fold_benchmark --enable-pretrain` would
look for, so downstream commands skip pretraining. Idempotent: exits 0 if the
checkpoint already exists.

Used by parallel/lane0.sh and parallel/lane1.sh (generated by parallel/plan.py).
"""
import argparse
import os
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from benchmarking.run_single_fold_benchmark import (  # noqa: E402
    load_and_run_framework,
    setup_pretrain_training,
)
from benchmarking.utils import get_pretrained_model_path  # noqa: E402

SYNTHETIC_ROOT = PROJECT_ROOT / "data" / "pretrain_data"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--framework", required=True)
    ap.add_argument("--task", required=True, choices=["ocr", "omr"])
    ap.add_argument("--model", default="default")
    ap.add_argument("--pretrain-dir", default=None,
                    help="omit for synthetic data (data/pretrain_data/<task>)")
    ap.add_argument("--edition", default="diplomatic")
    ap.add_argument("--check", action="store_true",
                    help="print the resolved paths and exit without training")
    a = ap.parse_args()

    pretrain_dir = Path(a.pretrain_dir) if a.pretrain_dir else None
    data_root = pretrain_dir or (SYNTHETIC_ROOT / a.task)
    train_json = data_root / f"annotations-{a.edition}" / f"{a.task}_train.json"
    target = get_pretrained_model_path(a.framework, a.task, a.model, pretrain_dir)

    if a.check:
        print(f"data_root={data_root}")
        print(f"train_json={train_json} exists={train_json.exists()}")
        print(f"checkpoint={target} exists={target.exists()}")
        return 0 if train_json.exists() else 2

    if target.exists():
        print(f"SKIP pretrain: {target} already exists")
        return 0
    if not train_json.exists():
        print(f"ERROR: missing {train_json}", file=sys.stderr)
        return 2

    ns = argparse.Namespace(
        debug=False,
        task=a.task,
        framework=a.framework,
        model_name=a.model,
        edition=a.edition,
        enable_pretrain=True,
        pretrain_dir=pretrain_dir,
        augment=True,
        train_dir=None,
        test_dir=None,
        data_dir=None,
        fold=0,
        sequential_step=None,
        sequential_strategy=None,
    )
    setup_dict = setup_pretrain_training(ns, a.task, target)
    print(f"PRETRAIN {a.framework}/{a.task}/{a.model} -> {target}", flush=True)
    load_and_run_framework(a.framework, setup_dict)
    print(f"PRETRAIN_DONE {target}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
